import { Card, CardHeader, PageHeader, Segmented, Skeleton, EmptyState, Notice, Spinner, fmtInt, fmtNum } from '../components/ui';
import { Chart, useChartColors } from '../components/Chart';
import { useUrlState } from '../lib/urlState';
import { query, useDbState, ensureTable, type QueryResult } from '../lib/db';
import { getLastSql } from '../lib/history';
import { histogram, pearson, describe as describeStats } from '../lib/stats';
import { useSummary, get } from '../lib/data';
import { PROFILING_BASE } from '../config';
import { DIVERGING } from '../lib/palette';

const REPORTS = [
  { value: 'ydata', file: 'ydata_profiling.html', label: 'YData Profiling' },
  { value: 'sweetviz', file: 'sweetviz_1990s_vs_2010s.html', label: 'Sweetviz: 1990s vs 2010s' },
] as const;

function useReportAvailable(file: string): 'loading' | 'yes' | 'no' {
  const [s, setS] = useState<'loading' | 'yes' | 'no'>('loading');
  useEffect(() => {
    let a = true;
    setS('loading');
    fetch(new URL(PROFILING_BASE + file, document.baseURI).href)
      .then(async (r) => {
        if (!r.ok) return 'no' as const;
        const head = (await r.text()).slice(0, 4000);
        // a static-host SPA fallback would return the app's own index.html
        return head.includes('id="root"') && head.includes('SonicAtlas') ? ('no' as const) : ('yes' as const);
      })
      .catch(() => 'no' as const)
      .then((v) => { if (a) setS(v); });
    return () => { a = false; };
  }, [file]);
  return s;
}

const DEFAULT_SQL = 'SELECT * FROM tracks USING SAMPLE 5000 ROWS';

export default function Profile() {
  const [tab, setTab] = useUrlState<'quick' | 'ydata' | 'sweetviz'>('r', 'quick');
  const [sqlParam] = useUrlState<string>('sql', '');
  const summary = useSummary();
  const prof = get<any>(summary.status === 'ready' ? summary.data : null, 'profiling');
  const report = REPORTS.find((r) => r.value === tab);

  return (
    <div>
      <PageHeader kicker="Data Profile" title="Know your data before you trust it">
        Automated profiling reports generated in the analysis pipeline, plus a quick profile of any Query Studio result computed in your browser.
      </PageHeader>
      <div className="mb-4">
        <Segmented label="View" hideLabel value={tab} onChange={setTab} options={[{ value: 'quick', label: 'Quick profile (live)' }, ...REPORTS.map((r) => ({ value: r.value, label: r.label }))]} />
      </div>
      {tab === 'quick' ? <QuickProfile initialSql={sqlParam || getLastSql() || DEFAULT_SQL} /> : report && <ReportFrame file={report.file} label={report.label} prof={prof} />}
    </div>
  );
}

function ReportFrame({ file, label, prof }: { file: string; label: string; prof: any }) {
  const ok = useReportAvailable(file);
  const url = PROFILING_BASE + file;
  return (
    <Card>
      <CardHeader title={label}
        subtitle={prof ? (file.startsWith('ydata') ? `${fmtInt(prof.sample_n)}-row sample, generated in ${fmtNum(prof.ydata_seconds, 1)} s with ${fmtInt(prof.ydata_alerts)} alerts` : `${fmtInt(prof.sweetviz_n_1990s)} tracks from the 1990s vs ${fmtInt(prof.sweetviz_n_2010s)} from the 2010s`) : 'Generated by the profiling notebook'}
        actions={ok === 'yes' && <a className="btn-secondary btn-sm" href={url} target="_blank" rel="noopener">Open in new tab <ExternalLink className="h-3.5 w-3.5" aria-hidden /></a>} />
      {ok === 'loading' ? <Skeleton className="m-4 h-[600px]" /> : ok === 'no' ? (
        <EmptyState title="Report not available yet" icon="data">
          <code className="kbd">{file}</code> has not been copied to <code className="kbd">web/public/profiling/</code>. Run the profiling notebook (09) and the web export.
        </EmptyState>
      ) : (
        <iframe title={label} src={url} className="h-[78vh] w-full rounded-b-xl border-0 bg-white" loading="lazy" sandbox="allow-scripts allow-same-origin allow-popups" />
      )}
    </Card>
  );
}

function QuickProfile({ initialSql }: { initialSql: string }) {
  const db = useDbState();
  const c = useChartColors();
  const [sql, setSql] = useState(initialSql);
  const [res, setRes] = useState<QueryResult | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  const run = async (s: string) => {
    setBusy(true); setErr(null);
    try {
      if (/\bgenre_tracks\b/i.test(s)) await ensureTable('genre_tracks');
      if (/\bembeddings\b/i.test(s)) await ensureTable('embeddings');
      setRes(await query(s));
    } catch (e: any) { setErr(String(e?.message ?? e)); setRes(null); } finally { setBusy(false); }
  };
  useEffect(() => { if (db.phase === 'ready') void run(sql); /* eslint-disable-next-line */ }, [db.phase]);

  const profile = useMemo(() => {
    if (!res) return null;
    return res.columns.map((col) => {
      const vals = res.rows.map((r) => r[col]);
      const missing = vals.filter((v) => v === null || v === undefined || (typeof v === 'number' && Number.isNaN(v))).length;
      const present = vals.filter((v) => v !== null && v !== undefined);
      const numeric = present.length > 0 && present.every((v) => typeof v === 'number');
      const distinct = new Set(present.map((v) => (typeof v === 'object' ? JSON.stringify(v) : v))).size;
      let top: [string, number][] = [];
      if (!numeric) {
        const m = new Map<string, number>();
        for (const v of present) { const k = String(v); m.set(k, (m.get(k) ?? 0) + 1); }
        top = [...m.entries()].sort((a, b) => b[1] - a[1]).slice(0, 5);
      }
      return { col, type: res.types[res.columns.indexOf(col)], missing, distinct, numeric, values: numeric ? (present as number[]) : [], top };
    });
  }, [res]);

  const numericCols = profile?.filter((p) => p.numeric && p.distinct > 1) ?? [];

  const corr = useMemo(() => {
    if (!res || numericCols.length < 2) return null;
    const cols = numericCols.slice(0, 16).map((p) => p.col);
    const arr = cols.map((cname) => res.rows.map((r) => r[cname] as number));
    const data: [number, number, number][] = [];
    for (let i = 0; i < cols.length; i++) for (let j = 0; j < cols.length; j++) {
      // pairwise complete observations
      const x: number[] = [], y: number[] = [];
      for (let k = 0; k < arr[i].length; k++) { const a = arr[i][k], b = arr[j][k]; if (typeof a === 'number' && typeof b === 'number' && Number.isFinite(a) && Number.isFinite(b)) { x.push(a); y.push(b); } }
      data.push([j, i, Number(pearson(x, y).toFixed(3))]);
    }
    return {
      tooltip: { formatter: (p: any) => `${cols[p.value[1]]} ~ ${cols[p.value[0]]}: r = ${p.value[2]}` },
      grid: { left: 110, right: 30, top: 10, bottom: 100 },
      xAxis: { type: 'category', data: cols, axisLabel: { rotate: 45, fontSize: 10 }, splitArea: { show: false } },
      yAxis: { type: 'category', data: cols, axisLabel: { fontSize: 10 } },
      visualMap: { min: -1, max: 1, calculable: true, orient: 'vertical', right: 0, top: 'center', inRange: { color: DIVERGING }, textStyle: { color: c.subtle }, itemHeight: 160 },
      series: [{ type: 'heatmap', data, label: { show: cols.length <= 10, fontSize: 9, color: '#111', formatter: (p: any) => p.value[2].toFixed(2) } }],
    };
  }, [res, numericCols, c]);

  return (
    <div className="space-y-6">
      <Card>
        <CardHeader title="Profile a query result" subtitle="Defaults to the last Query Studio query in this tab; open from Query Studio with 'Profile this result'" />
        <form className="flex flex-col gap-2 p-4 md:flex-row" onSubmit={(e) => { e.preventDefault(); void run(sql); }}>
          <label htmlFor="prof-sql" className="sr-only">SQL to profile</label>
          <textarea id="prof-sql" className="input min-h-[72px] font-mono text-xs" value={sql} onChange={(e) => setSql(e.target.value)} />
          <button type="submit" className="btn-primary md:self-start" disabled={busy || db.phase !== 'ready'}>{busy ? <Spinner /> : <Play className="h-4 w-4" aria-hidden />} Profile</button>
        </form>
        {err && <div className="px-4 pb-4"><Notice tone="error">{err}</Notice></div>}
      </Card>
      {!res ? (busy || db.phase !== 'ready' ? <Skeleton className="h-96" /> : <Card><EmptyState title="Nothing profiled yet" action={<Link className="btn-secondary" to="/query">Go to Query Studio</Link>} /></Card>) : (
        <>
          <Card>
            <CardHeader title={`${fmtInt(res.rows.length)} rows x ${res.columns.length} columns`} subtitle={`Query took ${res.ms.toFixed(1)} ms; statistics computed in the browser (n-1 variance, Tukey quartiles, G1 / G2)`} />
            <div className="overflow-x-auto p-4">
              <table className="w-full min-w-max text-sm" data-testid="profile-table">
                <caption className="sr-only">Column profile</caption>
                <thead><tr className="text-xs text-subtle">{['Column', 'Type', 'Missing', 'Distinct', 'Mean', 'Std', 'Min', 'Q1', 'Median', 'Q3', 'Max', 'G1', 'G2', 'Distribution / top values'].map((h) => <th key={h} scope="col" className="px-2 py-1.5 text-left">{h}</th>)}</tr></thead>
                <tbody>
                  {profile!.map((p) => {
                    const s = p.numeric ? describeStats(p.values) : null;
                    const h = p.numeric ? histogram(p.values, 20) : null;
                    const maxC = h ? Math.max(...h.counts, 1) : 1;
                    return (
                      <tr key={p.col} className="border-t border-border">
                        <th scope="row" className="px-2 py-1.5 text-left font-medium">{p.col}</th>
                        <td className="px-2 font-mono text-[11px] text-subtle">{p.type}</td>
                        <td className={`px-2 font-mono text-xs ${p.missing ? 'text-danger' : ''}`}>{fmtInt(p.missing)}{p.missing ? ` (${((100 * p.missing) / res.rows.length).toFixed(1)}%)` : ''}</td>
                        <td className="px-2 font-mono text-xs">{fmtInt(p.distinct)}</td>
                        {s ? [s.mean, s.std, s.min, s.q1, s.median, s.q3, s.max, s.g1, s.g2].map((v, i) => <td key={i} className="px-2 text-right font-mono text-xs">{fmtNum(v, 3)}</td>) : Array.from({ length: 9 }, (_, i) => <td key={i} className="px-2 text-center text-subtle">-</td>)}
                        <td className="px-2 py-1">
                          {h ? (
                            <svg width="140" height="28" role="img" aria-label={`Histogram of ${p.col}`}>
                              {h.counts.map((cnt, i) => <rect key={i} x={i * 7} y={28 - (26 * cnt) / maxC} width={6} height={(26 * cnt) / maxC} fill={c.palette[0]} />)}
                            </svg>
                          ) : <span className="text-xs text-subtle">{p.top.map(([k, v]) => `${k.length > 18 ? k.slice(0, 16) + '...' : k} (${v})`).join(', ')}</span>}
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          </Card>
          <Card>
            <CardHeader title="Correlation matrix" subtitle="Pearson r, pairwise complete observations, numeric columns (up to 16)" />
            <div className="p-3">{corr ? <Chart option={corr} height={Math.max(360, 30 * Math.min(16, numericCols.length) + 140)} ariaLabel="Heatmap of Pearson correlations between numeric columns" /> : <EmptyState title="Need at least two numeric columns" />}</div>
          </Card>
        </>
      )}
    </div>
  );
}
